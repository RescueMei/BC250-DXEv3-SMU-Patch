#!/usr/bin/env python3
"""Generate SMUPatchTable.h from payload/patches.hex.

Replicates the parser in bc250-smu-unlock/patcher.py:
  - Type-02 records set the 16-bit extended linear base (base = addr << 4).
  - Type-00 records are data records placed at base + addr.
Writes the C patch table consumed by the DXE driver (payload/build.sh).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEX = HERE / "patches.hex"
OUT = HERE.parent / "BC250DXEv3SMUPatchPkg" / "BC250DXEv3SMUPatchDxe" / "SMUPatchTable.h"


def read_hex(path):
    sites, base = [], 0
    for line in path.open():
        line = line.strip()
        if not line.startswith(":"):
            continue
        count = int(line[1:3], 16)
        addr = int(line[3:7], 16)
        typ = int(line[7:9], 16)
        data = bytes.fromhex(line[9:9 + count * 2])
        if typ == 2:
            base = int(line[9:13], 16) << 4
        elif typ == 0:
            sites.append((base + addr, data))
    return sorted(sites)


def main():
    sites = read_hex(HEX)
    out = sys.stdout if OUT is None else open(OUT, "w")
    out.write("// Generated by payload/gen_patch_table.py from payload/patches.hex - do not edit.\n")
    out.write("#ifndef BC250_SMU_PATCH_TABLE_H_\n#define BC250_SMU_PATCH_TABLE_H_\n\n")
    out.write("// Total patch sites: %d\n" % len(sites))
    out.write("STATIC CONST SMU_PATCH_SITE  mSmuPatchSites[] = {\n")
    for addr, data in sites:
        bytestr = ", ".join("0x%02X" % b for b in data)
        out.write("  { 0x%05X, %d, { %s } },\n" % (addr, len(data), bytestr))
    out.write("};\n\n")
    out.write("#define SMU_PATCH_TABLE_SIZE  (sizeof (mSmuPatchSites) / sizeof (mSmuPatchSites[0]))\n\n")
    out.write("#endif // BC250_SMU_PATCH_TABLE_H_\n")
    if out is not sys.stdout:
        out.close()
        sys.stderr.write("wrote %s (%d sites)\n" % (OUT, len(sites)))


if __name__ == "__main__":
    main()

#!/usr/bin/env bash
#
# Build the BC-250 SMU metrics-patch payload inside the Xtensa toolchain
# container and emit the headers the DXE driver embeds:
#
#   smu_patch.bin / SmuPatchPayload.h   native Xtensa payload
#   SmuPatchMeta.h                      link base + smu_patch_entry offset
#
# Usage: ./build.sh
# Env:   CONTAINER_ENGINE (podman), XTENSA_IMAGE, NO_CONTAINER=1 (host toolchain)
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
DRIVER_DIR="$REPO_DIR/BC250DXEv3SMUPatchPkg/BC250DXEv3SMUPatchDxe"
CONTAINER_ENGINE="${CONTAINER_ENGINE:-podman}"
XTENSA_IMAGE="${XTENSA_IMAGE:-localhost/bc250-xtensa:latest}"
NO_CONTAINER="${NO_CONTAINER:-0}"
BASE=0x3ae00

run_make() {
  if [[ "$NO_CONTAINER" == "1" ]]; then
    ( cd "$SCRIPT_DIR" && eval "$1" )
  else
    "$CONTAINER_ENGINE" run --rm -v "$REPO_DIR:$REPO_DIR:Z" -w "$SCRIPT_DIR" \
      "$XTENSA_IMAGE" bash -c "export PATH=/opt/xtensa/xtensa-esp-elf/bin:\$PATH; $1"
  fi
}

echo "== smu_patch.bin (native Xtensa metrics patch)"
run_make "make -B smu_patch.bin SmuPatchPayload.h"

echo "== verify + emit meta"
run_make '
  set -e
  nm=$(xtensa-esp32-elf-nm smu_patch.elf)
  entry=$(echo "$nm" | awk "/ T smu_patch_entry\$/{print \$1}")
  cc=$(echo "$nm" | awk "/ T smu_clamp_current\$/{print \$1}")
  ca=$(echo "$nm" | awk "/ T smu_clamp_average\$/{print \$1}")
  sp=$(echo "$nm" | awk "/ T smu_spare_entry\$/{print \$1}")
  undef=$(xtensa-esp32-elf-nm -u smu_patch.elf)
  [ -n "$entry" ] || { echo "  ERROR: smu_patch_entry not found"; exit 1; }
  [ -n "$cc" ] || { echo "  ERROR: smu_clamp_current not found"; exit 1; }
  [ -n "$ca" ] || { echo "  ERROR: smu_clamp_average not found"; exit 1; }
  [ -n "$sp" ] || { echo "  ERROR: smu_spare_entry not found"; exit 1; }
  [ -z "$undef" ] || { echo "  ERROR: undefined symbols:"; echo "$undef"; exit 1; }
  # FP-assist guard: the SMU Xtensa core has no windowed FP-assist helpers.
  bad=$(xtensa-esp32-elf-objdump -d smu_patch.elf | grep -cE "float|libgcc|__.*sf|__.*df" || true)
  base=$((0x3ae00))
  off=$((0x$entry - base)); occ=$((0x$cc - base)); oca=$((0x$ca - base)); osp=$((0x$sp - base))
  printf "  entry=0x%s(0x%x) clamp_cur=0x%s(0x%x) clamp_avg=0x%s(0x%x) bin=%s bytes fp=%s\n" \
    "$entry" "$off" "$cc" "$occ" "$ca" "$oca" "$(wc -c < smu_patch.bin)" "$bad"
  {
    echo "/* Generated by payload/build.sh - do not edit. */"
    echo "#ifndef BC250_SMU_PATCH_META_H"
    echo "#define BC250_SMU_PATCH_META_H"
    echo "#define SMU_PATCH_PAYLOAD_BASE         0x$(printf %x "$base")u"
    echo "#define SMU_PATCH_ENTRY_OFFSET         0x$(printf %x "$off")u"
    echo "#define SMU_PATCH_CLAMP_CURRENT_OFFSET 0x$(printf %x "$occ")u"
    echo "#define SMU_PATCH_CLAMP_AVERAGE_OFFSET 0x$(printf %x "$oca")u"
    echo "#define SMU_PATCH_SPARE_OFFSET         0x$(printf %x "$osp")u"
    echo "#endif"
  } > SmuPatchMeta.h
  echo "  OK"
'

echo "== embed payload headers"
cp -f "$SCRIPT_DIR/SmuPatchPayload.h" "$DRIVER_DIR/SmuPatchPayload.h"
cp -f "$SCRIPT_DIR/SmuPatchMeta.h"    "$DRIVER_DIR/SmuPatchMeta.h"
echo "   $DRIVER_DIR/SmuPatchPayload.h"
echo "   $DRIVER_DIR/SmuPatchMeta.h"
